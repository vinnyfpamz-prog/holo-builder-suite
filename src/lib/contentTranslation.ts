const patternTranslations: Array<[RegExp, string]> = [
  [/^Arte Digital (\d+)$/i, 'Digital Artwork $1'],
  [/^Design Criativo (\d+)$/i, 'Creative Design $1'],
  [/^Arte Criativa (\d+)$/i, 'Creative Artwork $1'],
  [/^Banner Shopbox (\d+)$/i, 'Shopbox Banner $1'],
  [/^Arte PicsArt (\d+)$/i, 'PicsArt Artwork $1'],
  [/^Ilustração Digital (\d+)$/i, 'Digital Illustration $1'],
  [/^Arte WhatsApp (\d+)$/i, 'WhatsApp Artwork $1'],
  [/^Foto IMG (\d+)$/i, 'Photo IMG $1'],
  [/^Vídeo Shopbox (\d+)$/i, 'Shopbox Video $1'],
];

export function translateContent(value: string | null | undefined, language: SiteLanguage): string {
  if (!value) return '';
  if (language === 'pt') return value;
  if (exactTranslations[value]) return exactTranslations[value];

  for (const [pattern, replacement] of patternTranslations) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }

  return value;
}

export function translateCategoryName(name: string | null | undefined, slug: string | null | undefined, language: SiteLanguage): string {
  if (language === 'pt') return name || 'Projeto';
  const bySlug: Record<string, string> = {
    digital: 'Digital Art',
    impressos: 'Print Design',
    video: 'Videos',
    web: 'Web',
    identidade: 'Visual Identity',
    especiais: 'Special Projects',
  };
  return (slug && bySlug[slug]) || translateContent(name || 'Projeto', language);
}